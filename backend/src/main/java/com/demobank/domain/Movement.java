package com.demobank.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.ForeignKey;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import java.math.BigDecimal;
import java.time.Instant;
import java.util.Objects;

/**
 * A single statement line on one {@link Account}.
 *
 * <p>A transfer produces exactly two movements - a {@link MovementType#DEBIT} on
 * the source account and a {@link MovementType#CREDIT} on the destination - and
 * both are written inside the same database transaction as the two balance
 * updates. If any of the four statements fails, none of them is committed.</p>
 *
 * <p>{@link #balanceAfter} snapshots the account balance immediately after this
 * line was applied. It makes a statement reproducible years later without
 * replaying the entire history, and it lets a reader (or an auditor) spot an
 * inconsistency straight away.</p>
 */
@Entity
@Table(name = "movements")
public class Movement {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "account_id", nullable = false,
            foreignKey = @ForeignKey(name = "fk_movements_account"))
    private Account account;

    @Column(name = "executed_at", nullable = false)
    private Instant executedAt;

    @Column(name = "description", nullable = false, length = 140)
    private String description;

    @Enumerated(EnumType.STRING)
    @Column(name = "type", nullable = false, length = 10)
    private MovementType type;

    /** Positive magnitude; the direction is given by {@link #type}. */
    @Column(name = "amount", nullable = false, precision = 19, scale = 2)
    private BigDecimal amount;

    @Column(name = "balance_after", nullable = false, precision = 19, scale = 2)
    private BigDecimal balanceAfter;

    /**
     * Originating transfer, when this line was generated by one. {@code null}
     * for seed movements imported from an external statement.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "transfer_id", foreignKey = @ForeignKey(name = "fk_movements_transfer"))
    private Transfer transfer;

    /** Required by JPA. */
    protected Movement() {
    }

    /**
     * Creates a movement.
     *
     * <p>{@code executedAt} is passed in rather than read from the clock here,
     * so that the two legs of one transfer carry the <em>same</em> instant. It
     * also makes the entity trivially testable: a test can produce a statement
     * with a deterministic history instead of one that depends on when it
     * ran.</p>
     */
    public Movement(Account account, MovementType type, BigDecimal amount,
                    BigDecimal balanceAfter, String description, Transfer transfer,
                    Instant executedAt) {
        this.account = account;
        this.type = type;
        this.amount = amount;
        this.balanceAfter = balanceAfter;
        this.description = description;
        this.transfer = transfer;
        this.executedAt = executedAt;
    }

    public Long getId() {
        return id;
    }

    public Account getAccount() {
        return account;
    }

    public Instant getExecutedAt() {
        return executedAt;
    }

    public String getDescription() {
        return description;
    }

    public MovementType getType() {
        return type;
    }

    public BigDecimal getAmount() {
        return amount;
    }

    public BigDecimal getBalanceAfter() {
        return balanceAfter;
    }

    public Transfer getTransfer() {
        return transfer;
    }

    @Override
    public boolean equals(Object other) {
        if (this == other) {
            return true;
        }
        if (!(other instanceof Movement movement) || id == null) {
            return false;
        }
        return id.equals(movement.id);
    }

    @Override
    public int hashCode() {
        return Objects.hashCode(id);
    }

    @Override
    public String toString() {
        return "Movement{id=" + id + ", type=" + type + ", amount=" + amount
                + ", executedAt=" + executedAt + '}';
    }
}
